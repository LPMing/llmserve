#!/usr/bin/env python3
"""Generate a bounded EP64 request-concurrency characterization workload.

The generated bytes are not specified here.  Input/output token counts are
the only workload knobs; the simulator/replay derives KV and EP bytes from the
Qwen3 model and GateRouter.  The two explicit phase flags create a matched
cross-request control: active Decode requests emit EP only, while later new
requests emit P2D KV only.
"""

import argparse
import json
from pathlib import Path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--decode-count", type=int, default=16)
    parser.add_argument("--p2d-count", type=int, default=64)
    parser.add_argument("--decode-input", type=int, default=128)
    parser.add_argument("--decode-output", type=int, default=64)
    parser.add_argument("--p2d-input", type=int, default=2048)
    parser.add_argument("--p2d-arrival-ns", type=int, default=20_000_000)
    args = parser.parse_args()
    if args.decode_count <= 0 or args.p2d_count <= 0:
        parser.error("request counts must be positive")
    rows = []
    for index in range(args.decode_count):
        rows.append({
            "request_id": "decode-%d" % index,
            "input_toks": args.decode_input,
            "output_toks": args.decode_output,
            "arrival_time_ns": 0,
            "emit_p2d": False,
            "emit_ep": True,
            "workload_role": "active_decode",
        })
    for index in range(args.p2d_count):
        rows.append({
            "request_id": "kv-%d" % index,
            "input_toks": args.p2d_input,
            "output_toks": 0,
            "arrival_time_ns": args.p2d_arrival_ns,
            "emit_p2d": True,
            "emit_ep": False,
            "workload_role": "new_p2d",
        })
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8") as stream:
        for row in rows:
            stream.write(json.dumps(row, separators=(",", ":")) + "\n")
    print(json.dumps({
        "output": str(args.output),
        "decode_count": args.decode_count,
        "p2d_count": args.p2d_count,
        "p2d_input_tokens": args.p2d_input,
        "synthetic_byte_override": False,
    }, indent=2))


if __name__ == "__main__":
    main()
