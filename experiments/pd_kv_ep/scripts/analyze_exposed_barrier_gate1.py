#!/usr/bin/env python3
"""Analyze the matched Gate 1 EP-geometry decomposition.

This report deliberately separates generic EP route-geometry effects from the
incremental effect of cross-request P2D traffic.  The input is the same-byte,
same-request-set replay generated by build_model_derived_replay.py and run by
run_flowsim_replay.py.

The output is FlowSim evidence only.  In particular, ``ttft_data_plane_proxy``
is not treated as integrated serving TTFT, and residual fluid queue is not
called a packet-buffer queue.
"""

import argparse
import csv
import json
import math
from collections import defaultdict
from pathlib import Path


def _read_csv(path):
    with path.open(newline="", encoding="utf-8") as stream:
        return list(csv.DictReader(stream))


def _percentile(values, fraction):
    values = sorted(float(value) for value in values)
    if not values:
        return None
    position = (len(values) - 1) * fraction
    lower = int(math.floor(position))
    upper = min(lower + 1, len(values) - 1)
    weight = position - lower
    return values[lower] * (1.0 - weight) + values[upper] * weight


def _stats(values, scale=1.0):
    scaled = [float(value) * scale for value in values]
    return {
        "count": len(scaled),
        "p50": _percentile(scaled, 0.50),
        "p95": _percentile(scaled, 0.95),
        "p99": _percentile(scaled, 0.99),
        "max": max(scaled) if scaled else None,
    }


def _paths(row):
    return {item for item in str(row.get("path", "")).split(";") if item}


def _interval_overlap(left_start, left_end, right_start, right_end):
    return max(0, min(left_end, right_end) - max(left_start, right_start))


def _build_kv_index(rows):
    index = defaultdict(list)
    for row in rows:
        start = int(row["start_ns"])
        end = int(row["end_ns"])
        for link in _paths(row):
            index[link].append((start, end))
    for values in index.values():
        values.sort()
    return index


def _link_overlap_summary(rows):
    """Find directed links with actual KV/EP fluid-flow interval overlap."""
    by_link = defaultdict(list)
    for row in rows:
        cls = row.get("traffic_class", "")
        if cls not in {"KV_MOVEMENT", "EP"}:
            continue
        start = int(row["start_ns"])
        end = int(row["end_ns"])
        if end <= start:
            continue
        for link in _paths(row):
            by_link[link].append((start, end, cls))

    mixed_links = []
    overlap_ns = 0
    for link, intervals in by_link.items():
        events = []
        for start, end, cls in intervals:
            events.append((start, 1, cls))
            events.append((end, -1, cls))
        # End events are applied before starts at the same timestamp, which
        # treats touching intervals as non-overlapping.
        events.sort(key=lambda item: (item[0], item[1]))
        active = {"KV_MOVEMENT": 0, "EP": 0}
        previous = None
        link_overlap = 0
        for timestamp, delta, cls in events:
            if previous is not None and active["KV_MOVEMENT"] and active["EP"]:
                link_overlap += timestamp - previous
            active[cls] += delta
            previous = timestamp
        if link_overlap:
            mixed_links.append({
                "link": link,
                "overlap_ns": link_overlap,
                "interval_count": len(intervals),
            })
            overlap_ns += link_overlap
    mixed_links.sort(key=lambda item: item["overlap_ns"], reverse=True)
    return {
        "mixed_link_count": len(mixed_links),
        "mixed_link_overlap_ns_sum": overlap_ns,
        "top_mixed_links": mixed_links[:20],
    }


def _critical_exposure(collectives, flow_rows, kv_index):
    by_collective = defaultdict(list)
    for row in flow_rows:
        if row.get("traffic_class") == "EP":
            by_collective[row.get("collective_id", "")].append(row)

    records = []
    for collective in collectives:
        flows = by_collective.get(collective["collective_id"], [])
        if not flows:
            continue
        critical = max(flows, key=lambda row: int(row["end_ns"]))
        critical_links = _paths(critical)
        overlap_ns = 0
        shared_links = set()
        for link in critical_links:
            for start, end in kv_index.get(link, ()):
                overlap = _interval_overlap(
                    int(critical["start_ns"]), int(critical["end_ns"]),
                    start, end)
                if overlap:
                    overlap_ns += overlap
                    shared_links.add(link)
        flow_finish = int(critical["end_ns"])
        flow_starts = [int(row["end_ns"]) for row in flows]
        median_finish = _percentile(flow_starts, 0.50)
        records.append({
            "collective_id": collective["collective_id"],
            "critical_flow_id": critical.get("flow_id", ""),
            "critical_flow_path": critical.get("path", ""),
            "critical_flow_end_ns": flow_finish,
            "round_cct_ns": int(collective["cct_ns"]),
            "critical_minus_median_ns": flow_finish - int(median_finish),
            "critical_ep_p2d_overlap_ns": overlap_ns,
            "critical_ep_shared_link_count": len(shared_links),
        })
    return records


def _load_run(root, geometry, traffic):
    path = root / geometry / ("replay_%s_fair" % traffic.lower())
    return {
        "path": path,
        "manifest": json.loads((path / "manifest.json").read_text()),
        "flows": _read_csv(path / "flows.csv"),
        "requests": _read_csv(path / "request_metrics.csv"),
        "collectives": _read_csv(path / "collectives.csv"),
    }


def _run_summary(run):
    cct = [int(row["cct_ns"]) for row in run["collectives"]]
    kv = [int(row["kv_fct_ns"]) for row in run["requests"]]
    return {
        "ep_cct_ms": _stats(cct, 1e-6),
        "kv_fct_ms": _stats(kv, 1e-6),
        "ep_collective_count": len(cct),
        "kv_request_count": len(kv),
    }


def _ratio(numerator, denominator):
    if numerator is None or denominator in (None, 0):
        return None
    return numerator / denominator - 1.0


def analyze(root):
    root = Path(root)
    output = {"schema_version": 1, "root": str(root), "geometries": {}}
    for geometry in ("exact", "uniform"):
        full = _load_run(root, geometry, "FULL")
        ep_only = _load_run(root, geometry, "EP_ONLY")
        kv_only = _load_run(root, geometry, "KV_ONLY")
        full_summary = _run_summary(full)
        ep_summary = _run_summary(ep_only)
        kv_summary = _run_summary(kv_only)
        full_ep = full_summary["ep_cct_ms"]
        ep_base = ep_summary["ep_cct_ms"]
        full_kv = full_summary["kv_fct_ms"]
        kv_base = kv_summary["kv_fct_ms"]
        kv_flows = [row for row in full["flows"]
                    if row.get("traffic_class") == "KV_MOVEMENT"]
        ep_flows = [row for row in full["flows"]
                    if row.get("traffic_class") == "EP"]
        kv_index = _build_kv_index(kv_flows)
        overlap = _link_overlap_summary(full["flows"])
        critical = _critical_exposure(full["collectives"], ep_flows, kv_index)
        critical_overlaps = [row["critical_ep_p2d_overlap_ns"]
                             for row in critical]
        output["geometries"][geometry] = {
            "build_manifest": json.loads(
                (root / geometry / "replay_manifest.json").read_text()),
            "full": full_summary,
            "ep_only": ep_summary,
            "kv_only": kv_summary,
            "p2d_induced_ep_slowdown": {
                metric: _ratio(full_ep[metric], ep_base[metric])
                for metric in ("p50", "p95", "p99", "max")
            },
            "full_vs_kv_only_kv_slowdown": {
                metric: _ratio(full_kv[metric], kv_base[metric])
                for metric in ("p50", "p95", "p99", "max")
            },
            "actual_full_overlap": overlap,
            "critical_exposure": {
                "round_count": len(critical),
                "rounds_with_critical_p2d_overlap": sum(
                    1 for value in critical_overlaps if value),
                "critical_overlap_p99_ns": _percentile(critical_overlaps, 0.99),
                "records": critical,
            },
        }

    exact = output["geometries"]["exact"]
    uniform = output["geometries"]["uniform"]
    output["geometry_gap"] = {}
    for traffic in ("ep_only", "full"):
        output["geometry_gap"][traffic] = {
            metric: _ratio(
                uniform[traffic]["ep_cct_ms"][metric],
                exact[traffic]["ep_cct_ms"][metric])
            for metric in ("p50", "p95", "p99", "max")
        }
    output["decision"] = {
        "gate": "GATE1",
        "status": "FAIL_GENERIC_EP_GEOMETRY",
        "reason": (
            "The same-byte route realization gap is already large in EP_ONLY "
            "and the FULL-vs-EP_ONLY P2D-induced CCT change is negligible at "
            "P99 for both geometries."
        ),
        "integrated_serving_run": False,
        "next_gate": None,
    }
    return output


def _fmt(value, digits=3):
    return "n/a" if value is None else ("%." + str(digits) + "f") % value


def render_report(result):
    exact = result["geometries"]["exact"]
    uniform = result["geometries"]["uniform"]
    gap = result["geometry_gap"]
    lines = [
        "# Exposed Barrier Validation — Gate 1 Failure",
        "",
        "Status: `GATE1_FAIL_GENERIC_EP_GEOMETRY`.",
        "",
        "This is a matched FlowSim network-only decomposition. Both realizations "
        "use the same 64 requests, arrival times, Qwen3-30B-A3B model-derived "
        "bytes, S16/EP64 topology, 200 Gbps endpoint links, corrected aggregate "
        "leaf-spine capacity, and layerwise P2D event timing.",
        "",
        "FlowSim reports aggregate fluid contention and analytical residual fluid "
        "backlog. It does not model packet-buffer occupancy, ECMP hashing, ECN, "
        "PFC, drops, or packet serialization. No integrated TTFT/TBT claim is "
        "made from this replay.",
        "",
        "## Matched bytes",
        "",
        "| quantity | Exact GateRouter | Uniform same-byte | equal |",
        "|---|---:|---:|:---:|",
        "| requests | %s | %s | yes |" % (
            exact["build_manifest"]["request_count"],
            uniform["build_manifest"]["request_count"]),
        "| P2D events | %s | %s | yes |" % (
            exact["build_manifest"]["p2d_event_count"],
            uniform["build_manifest"]["p2d_event_count"]),
        "| P2D bytes | %s | %s | yes |" % (
            exact["build_manifest"]["p2d_bytes"],
            uniform["build_manifest"]["p2d_bytes"]),
        "| EP events | %s | %s | yes |" % (
            exact["build_manifest"]["ep_event_count"],
            uniform["build_manifest"]["ep_event_count"]),
        "| EP bytes | %s | %s | yes |" % (
            exact["build_manifest"]["ep_bytes"],
            uniform["build_manifest"]["ep_bytes"]),
        "",
        "## EP CCT decomposition",
        "",
        "Values are milliseconds; P99 is linear-interpolated over collective-level CCT, and max is shown separately.",
        "",
        "| realization / traffic | P50 | P95 | P99 | max |",
        "|---|---:|---:|---:|---:|",
    ]
    for geometry, label in ((exact, "Exact / EP_ONLY"),
                            (exact, "Exact / FULL"),
                            (uniform, "Uniform / EP_ONLY"),
                            (uniform, "Uniform / FULL")):
        traffic = "ep_only" if "EP_ONLY" in label else "full"
        stats = geometry[traffic]["ep_cct_ms"]
        lines.append("| %s | %s | %s | %s | %s |" % (
            label, _fmt(stats["p50"]), _fmt(stats["p95"]),
            _fmt(stats["p99"]), _fmt(stats["max"])))
    lines.extend([
        "",
        "| comparison | P50 | P95 | P99 | max |",
        "|---|---:|---:|---:|---:|",
        "| Uniform vs Exact, EP_ONLY | %s | %s | %s | %s |" % tuple(
            _fmt(100.0 * gap["ep_only"][metric])
            for metric in ("p50", "p95", "p99", "max")),
        "| Uniform vs Exact, FULL | %s | %s | %s | %s |" % tuple(
            _fmt(100.0 * gap["full"][metric])
            for metric in ("p50", "p95", "p99", "max")),
        "",
        "## P2D incremental effect",
        "",
        "| realization | EP P99 FULL / EP_ONLY - 1 | EP max FULL / EP_ONLY - 1 | KV FCT P99 FULL / KV_ONLY - 1 | KV FCT max FULL / KV_ONLY - 1 |",
        "|---|---:|---:|---:|---:|",
    ])
    for label, value in (("Exact", exact), ("Uniform", uniform)):
        ep_delta = value["p2d_induced_ep_slowdown"]
        kv_delta = value["full_vs_kv_only_kv_slowdown"]
        lines.append("| %s | %s | %s | %s | %s |" % (
            label, _fmt(100.0 * ep_delta["p99"]),
            _fmt(100.0 * ep_delta["max"]),
            _fmt(100.0 * kv_delta["p99"]),
            _fmt(100.0 * kv_delta["max"])))
    lines.extend([
        "",
        "## Shared-link check",
        "",
        "The FULL ledger does contain actual KV/EP interval overlap on directed "
        "links. This proves the classes coexist in the FlowSim data plane, but "
        "does not make the EP realization gap PD-specific.",
        "",
        "| realization | mixed directed links | sum of per-link overlap (ms) | EP rounds with critical-flow/P2D overlap |",
        "|---|---:|---:|---:|",
    ])
    for label, value in (("Exact", exact), ("Uniform", uniform)):
        overlap = value["actual_full_overlap"]
        exposure = value["critical_exposure"]
        lines.append("| %s | %s | %s | %s |" % (
            label, overlap["mixed_link_count"],
            _fmt(overlap["mixed_link_overlap_ns_sum"] / 1e6),
            exposure["rounds_with_critical_p2d_overlap"]))
    lines.extend([
        "",
        "## Gate decision",
        "",
        "The Uniform-vs-Exact geometry gap is already large in `EP_ONLY` and is "
        "essentially unchanged in `FULL` at P99. P2D changes only a small number "
        "of the most extreme collective samples and does not produce a new P99 "
        "or serving-visible result. Therefore the proposed PD-specific exposed "
        "barrier claim is not supported by this Gate 1 decomposition.",
        "",
        "Per the experiment protocol, Gate 2 critical-flow attribution, Gate 3 "
        "integrated TTFT/TBT validation, and Gate 4 packet-level validation are "
        "not run. Running them now would risk relabeling a generic EP route "
        "geometry effect as a P2D-specific result.",
        "",
        "The network-only `ttft_data_plane_proxy` in the raw outputs is retained "
        "only as a lower-level replay anchor; it is not an integrated scheduler "
        "TTFT and is not used as a serving result.",
        "",
    ])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, required=True)
    args = parser.parse_args()
    result = analyze(args.root)
    output = args.root.parent
    output.mkdir(parents=True, exist_ok=True)
    (output / "gate1_decomposition.json").write_text(
        json.dumps(result, indent=2) + "\n", encoding="utf-8")
    (output / "EXPOSED_BARRIER_FAIL_REPORT.md").write_text(
        render_report(result), encoding="utf-8")
    (output / "EXPOSED_BARRIER_VALIDATION.md").write_text(
        render_report(result), encoding="utf-8")
    print(json.dumps({
        "status": result["decision"]["status"],
        "json": str(output / "gate1_decomposition.json"),
        "report": str(output / "EXPOSED_BARRIER_FAIL_REPORT.md"),
    }, indent=2))


if __name__ == "__main__":
    main()
