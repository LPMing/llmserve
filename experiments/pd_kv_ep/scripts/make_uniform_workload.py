#!/usr/bin/env python3
"""Create a bounded native-token serving workload for timing gates.

The script changes request-level workload parameters only.  KV and EP bytes
are still generated by LLMServingSim from the selected model/profile; this
file never writes a communication-size override.
"""

import argparse
import json
from pathlib import Path


def make_request(input_tokens, output_tokens, arrival_ns, request_id):
    return {
        "request_id": request_id,
        "input_toks": int(input_tokens),
        "output_toks": int(output_tokens),
        "arrival_time_ns": int(arrival_ns),
        "input_tok_ids": list(range(1, int(input_tokens) + 1)),
        "output_tok_ids": list(range(
            int(input_tokens) + 1,
            int(input_tokens) + int(output_tokens) + 1)),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--requests", type=int, required=True)
    parser.add_argument("--input-tokens", type=int, required=True)
    parser.add_argument("--output-tokens", type=int, required=True)
    parser.add_argument("--arrival-gap-ms", type=float, default=0.0)
    args = parser.parse_args()
    if args.requests < 1 or args.input_tokens < 1 or args.output_tokens < 1:
        raise SystemExit("requests, input-tokens, and output-tokens must be positive")
    gap_ns = int(round(args.arrival_gap_ms * 1_000_000.0))
    rows = [make_request(args.input_tokens, args.output_tokens,
                         index * gap_ns, index)
            for index in range(args.requests)]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8") as stream:
        for row in rows:
            stream.write(json.dumps(row) + "\n")
    print("wrote", args.output, "requests", len(rows),
          "input_tokens", args.input_tokens,
          "output_tokens", args.output_tokens,
          "arrival_gap_ms", args.arrival_gap_ms)


if __name__ == "__main__":
    main()
